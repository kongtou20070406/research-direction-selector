"""Check collaborator contributions under contrib/<leaf>-<name>/ (0 LLM tokens).

Collaborators never edit program.json (it is regenerated by the exporter). They add a folder with
CLAIM.json and its evidence files; the project owner merges accepted claims into the project and
the next export mirrors them.

CLAIM.json: {"proposition": "<id in program.json>", "statement": "...",
             "strength": "observed|supported|proved", "evidence": ["<files in this folder>"],
             "falsifier": "what result would have refuted it", "author": "<name>"}
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
STRENGTHS = ("observed", "supported", "proved")


def check_contrib(root: Path = ROOT) -> list[str]:
    errors: list[str] = []
    contrib = root / "contrib"
    if not contrib.is_dir():
        return errors
    props = {p["id"] for p in json.loads((root / "program.json").read_text(encoding="utf-8-sig")).get("propositions", [])}
    for folder in sorted(p for p in contrib.iterdir() if p.is_dir()):
        claim_path = folder / "CLAIM.json"
        name = folder.relative_to(root).as_posix()
        if not claim_path.is_file():
            errors.append(f"{name}: missing CLAIM.json")
            continue
        try:
            claim = json.loads(claim_path.read_text(encoding="utf-8-sig"))
        except json.JSONDecodeError as exc:
            errors.append(f"{name}/CLAIM.json: invalid JSON ({exc})")
            continue
        if claim.get("proposition") not in props:
            errors.append(f"{name}: proposition {claim.get('proposition')!r} is not in program.json")
        for key in ("statement", "falsifier", "author"):
            if not str(claim.get(key, "")).strip():
                errors.append(f"{name}: missing '{key}'")
        if claim.get("strength") not in STRENGTHS:
            errors.append(f"{name}: strength must be one of {list(STRENGTHS)}")
        evidence = claim.get("evidence") or []
        if not evidence:
            errors.append(f"{name}: list at least one evidence file")
        for ev in evidence:
            p = (folder / ev).resolve()
            if folder.resolve() not in p.parents or not p.is_file():
                errors.append(f"{name}: evidence {ev!r} must be a file inside the folder")
        if claim.get("strength") == "proved" and not any(str(e).endswith(".lean") for e in evidence):
            errors.append(f"{name}: a proved claim needs a .lean file")
    return errors


def main() -> int:
    errors = check_contrib()
    for e in errors:
        print(f"  - {e}")
    print("CONTRIB " + ("FAILED" if errors else "OK"))
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
